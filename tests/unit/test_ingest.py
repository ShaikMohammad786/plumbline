"""Unit tests for repository ingest, classification, manifests, and walker."""

from pathlib import Path

from plumbline.config import PlumblineConfig
from plumbline.ingest.classify import classify_file
from plumbline.ingest.languages import detect_language
from plumbline.ingest.manifests import parse_manifest
from plumbline.ingest.walker import walk_repository
from plumbline.models import FileClass


def test_language_detection() -> None:
    assert detect_language(Path("main.py")) == "python"
    assert detect_language(Path("app.tsx")) == "tsx"
    assert detect_language(Path("server.go")) == "go"
    assert detect_language(Path("Dockerfile")) == "dockerfile"
    assert detect_language(Path("script"), first_line="#!/usr/bin/env python3") == "python"
    assert detect_language(Path("unknown.xyz")) is None


def test_file_classification() -> None:
    assert classify_file("src/service.py") == FileClass.PROD
    assert classify_file("tests/test_service.py") == FileClass.TEST
    assert classify_file("src/foo.test.ts") == FileClass.TEST
    assert classify_file("examples/quickstart.py") == FileClass.EXAMPLE
    assert classify_file("docs/guide.md") == FileClass.DOCS
    assert classify_file("vendor/lib.js") == FileClass.VENDOR
    assert classify_file("bundle.min.js") == FileClass.GENERATED
    assert (
        classify_file("autogen.go", first_lines="// Code generated by mockgen. DO NOT EDIT.")
        == FileClass.GENERATED
    )

    # Overrides
    overrides = {"src/legacy/*": "vendor"}
    assert classify_file("src/legacy/old.py", class_overrides=overrides) == FileClass.VENDOR


def test_all_manifest_parsers(tmp_path: Path) -> None:
    # 1. package.json
    pkg_json = tmp_path / "package.json"
    pkg_json.write_text(
        '{"dependencies": {"express": "^4.18.2"}, "devDependencies": {"jest": "^29.0.0"}, "peerDependencies": {"react": "^18.0.0"}}',
        encoding="utf-8",
    )
    npm_deps = parse_manifest(pkg_json, "package.json")
    assert len(npm_deps) == 3
    assert any(d.name == "express" and not d.dev for d in npm_deps)
    assert any(d.name == "jest" and d.dev for d in npm_deps)

    # 2. requirements.txt
    req_txt = tmp_path / "requirements.txt"
    req_txt.write_text("fastapi>=0.100.0\nuvicorn==0.23.2\n# comment\n", encoding="utf-8")
    py_deps = parse_manifest(req_txt, "requirements.txt")
    assert len(py_deps) == 2
    assert py_deps[0].name == "fastapi"

    # 3. pyproject.toml (PEP 621 + Poetry)
    pyproj = tmp_path / "pyproject.toml"
    pyproj.write_text(
        """
[project]
dependencies = ["requests>=2.28.0", "pydantic>=2.0"]
[project.optional-dependencies]
dev = ["pytest>=7.0"]

[tool.poetry.dependencies]
click = "^8.0"
[tool.poetry.group.test.dependencies]
coverage = "^7.0"
""",
        encoding="utf-8",
    )
    pyproj_deps = parse_manifest(pyproj, "pyproject.toml")
    assert any(d.name == "requests" and not d.dev for d in pyproj_deps)
    assert any(d.name == "pytest" and d.dev for d in pyproj_deps)
    assert any(d.name == "click" and not d.dev for d in pyproj_deps)
    assert any(d.name == "coverage" and d.dev for d in pyproj_deps)

    # 4. Pipfile
    pipfile = tmp_path / "Pipfile"
    pipfile.write_text('[packages]\nflask = "*"\n[dev-packages]\nblack = "*"\n', encoding="utf-8")
    pipfile_deps = parse_manifest(pipfile, "Pipfile")
    assert any(d.name == "flask" and not d.dev for d in pipfile_deps)
    assert any(d.name == "black" and d.dev for d in pipfile_deps)

    # 5. go.mod
    go_mod = tmp_path / "go.mod"
    go_mod.write_text(
        "module example.com/m\n\ngo 1.21\n\nrequire (\n\tgithub.com/gin-gonic/gin v1.9.1\n)\nrequire github.com/stretchr/testify v1.8.4\n",
        encoding="utf-8",
    )
    go_deps = parse_manifest(go_mod, "go.mod")
    assert len(go_deps) == 2

    # 6. Cargo.toml
    cargo_toml = tmp_path / "Cargo.toml"
    cargo_toml.write_text(
        '[package]\nname = "demo"\n\n[dependencies]\ntokio = "1.0"\n[dev-dependencies]\nassert_cmd = "2.0"\n',
        encoding="utf-8",
    )
    cargo_deps = parse_manifest(cargo_toml, "Cargo.toml")
    assert any(d.name == "tokio" and not d.dev for d in cargo_deps)
    assert any(d.name == "assert_cmd" and d.dev for d in cargo_deps)

    # 7. pom.xml
    pom_xml = tmp_path / "pom.xml"
    pom_xml.write_text(
        """
<project>
  <dependencies>
    <dependency>
      <groupId>org.springframework.boot</groupId>
      <artifactId>spring-boot-starter-web</artifactId>
      <version>3.1.0</version>
    </dependency>
    <dependency>
      <groupId>org.junit.jupiter</groupId>
      <artifactId>junit-jupiter</artifactId>
      <version>5.9.3</version>
      <scope>test</scope>
    </dependency>
  </dependencies>
</project>
""",
        encoding="utf-8",
    )
    maven_deps = parse_manifest(pom_xml, "pom.xml")
    assert any("spring-boot-starter-web" in d.name and not d.dev for d in maven_deps)
    assert any("junit-jupiter" in d.name and d.dev for d in maven_deps)

    # 8. build.gradle
    gradle = tmp_path / "build.gradle"
    gradle.write_text(
        """
dependencies {
    implementation 'com.google.guava:guava:32.0.0-jre'
    testImplementation 'junit:junit:4.13.2'
}
""",
        encoding="utf-8",
    )
    gradle_deps = parse_manifest(gradle, "build.gradle")
    assert any("guava" in d.name and not d.dev for d in gradle_deps)
    assert any("junit" in d.name and d.dev for d in gradle_deps)

    # 9. Gemfile
    gemfile = tmp_path / "Gemfile"
    gemfile.write_text("gem 'rails', '~> 7.0'\ngem 'puma'\n", encoding="utf-8")
    gem_deps = parse_manifest(gemfile, "Gemfile")
    assert len(gem_deps) == 2
    assert gem_deps[0].name == "rails"

    # 10. composer.json
    composer = tmp_path / "composer.json"
    composer.write_text(
        '{"require": {"monolog/monolog": "^3.0"}, "require-dev": {"phpunit/phpunit": "^10.0"}}',
        encoding="utf-8",
    )
    php_deps = parse_manifest(composer, "composer.json")
    assert any(d.name == "monolog/monolog" and not d.dev for d in php_deps)
    assert any(d.name == "phpunit/phpunit" and d.dev for d in php_deps)


def test_walker_filtering_and_limits(tmp_path: Path) -> None:
    # Create gitignored folder and files
    (tmp_path / ".git").mkdir()
    (tmp_path / ".git" / "HEAD").write_text("ref: refs/heads/main", encoding="utf-8")

    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "index.py").write_text("print('hello')", encoding="utf-8")

    # Binary file
    (tmp_path / "src" / "blob.bin").write_bytes(b"\x00\x01\x02\x03")

    # Large file (> 10KB when limit set to 5KB)
    (tmp_path / "src" / "large.txt").write_text("x" * 12000, encoding="utf-8")

    # .gitignore
    (tmp_path / ".gitignore").write_text("ignored_dir/\n*.tmp\n", encoding="utf-8")
    (tmp_path / "ignored_dir").mkdir()
    (tmp_path / "ignored_dir" / "secret.py").write_text("val = 1", encoding="utf-8")
    (tmp_path / "src" / "test.tmp").write_text("temp", encoding="utf-8")

    cfg = PlumblineConfig()
    cfg.scan.max_file_kb = 10

    result = walk_repository(tmp_path, cfg)
    paths = [f.path for f in result.files]

    assert "src/index.py" in paths
    assert ".gitignore" in paths
    assert "src/blob.bin" not in paths  # binary skipped
    assert "src/large.txt" not in paths  # large file skipped
    assert "ignored_dir/secret.py" not in paths  # gitignored
    assert "src/test.tmp" not in paths  # gitignored
    assert any("large.txt" in note for note in result.notes)
