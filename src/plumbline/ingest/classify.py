"""File classification for Plumbline."""

from __future__ import annotations

import fnmatch
from pathlib import PurePath
from typing import Optional

from plumbline.models import FileClass

TEST_DIR_NAMES = {"test", "tests", "__tests__", "spec", "specs", "golden"}
EXAMPLE_DIR_NAMES = {
    "example",
    "examples",
    "sample",
    "samples",
    "demo",
    "demos",
    "bench",
    "scripts",
    "fixtures",
}
DOCS_DIR_NAMES = {"docs", "doc"}
VENDOR_DIR_NAMES = {"vendor", "third_party", "node_modules"}

LOCKFILES = {
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "uv.lock",
    "pipfile.lock",
    "go.sum",
    "cargo.lock",
    "gemfile.lock",
}

DOC_EXTENSIONS = {".md", ".rst", ".txt"}

GENERATED_MARKERS = (
    "// Code generated",
    "/* Code generated",
    "@generated",
    "DO NOT EDIT",
    "This file is generated",
    "Auto-generated by",
)


def classify_file(
    relative_path: str,
    first_lines: Optional[str] = None,
    class_overrides: Optional[dict[str, str]] = None,
) -> FileClass:
    """Classify a file path into FileClass with high-speed pattern matching."""
    posix_path = PurePath(relative_path).as_posix()

    # 1. Config overrides take precedence
    if class_overrides:
        for pattern, cls_str in class_overrides.items():
            if fnmatch.fnmatch(posix_path, pattern):
                try:
                    return FileClass(cls_str)
                except ValueError:
                    # plumbline:ignore[SLP001] Invalid custom class override safely ignored
                    pass

    # 2. Generated checks
    if posix_path.endswith(".min.js") or posix_path.endswith(".min.css"):
        return FileClass.GENERATED
    if first_lines:
        for marker in GENERATED_MARKERS:
            if marker in first_lines:
                return FileClass.GENERATED

    parts = posix_path.split("/")
    filename = parts[-1].lower()
    dir_parts = set(parts[:-1])

    # 3. Test directory or test filename
    if dir_parts & TEST_DIR_NAMES:
        return FileClass.TEST
    if (
        filename.startswith("test_")
        or filename.endswith("_test.py")
        or filename.endswith("_test.go")
        or filename.endswith(".test.ts")
        or filename.endswith(".test.js")
        or filename.endswith(".test.tsx")
        or filename.endswith(".test.jsx")
        or filename.endswith(".spec.ts")
        or filename.endswith(".spec.js")
        or filename.endswith(".spec.tsx")
        or filename.endswith(".spec.jsx")
        or filename.endswith("_spec.rb")
    ):
        return FileClass.TEST

    # 4. Example patterns
    if dir_parts & EXAMPLE_DIR_NAMES or parts[0] == "bench":
        return FileClass.EXAMPLE

    # 5. Vendor / lockfiles
    if dir_parts & VENDOR_DIR_NAMES or filename in LOCKFILES:
        return FileClass.VENDOR

    # 6. Docs
    if dir_parts & DOCS_DIR_NAMES or any(filename.endswith(ext) for ext in DOC_EXTENSIONS):
        return FileClass.DOCS

    # 7. Default to production
    return FileClass.PROD
